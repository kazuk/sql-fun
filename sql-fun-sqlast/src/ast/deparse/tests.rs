#[rstest::rstest]
#[case::postgres(Dialect::postgres(), "$7", "$2")]
#[cfg_attr(feature = "sqlite", case::sqlite(Dialect::sqlite(), "?7", "?2"))]
fn renders_inserted_and_existing_bodies_without_source(
    #[case] dialect: Dialect,
    #[case] repeated: &str,
    #[case] other: &str,
) {
    let mut query = {
        let sql = format!("with old as (select {repeated} as id) select {other}, id from old");
        statement(&sql, dialect)
    };
    let definition = {
        let sql = format!("select {repeated} + {repeated} as id");
        CteDefinition::new("new", &statement(&sql, dialect)).unwrap()
    };
    query
        .ensure_with_clause()
        .unwrap()
        .insert(0, &definition)
        .unwrap();
    let rendered = query.deparse_sql(dialect).unwrap();
    assert!(rendered.contains(repeated));
    assert!(rendered.contains(other));
    assert!(rendered.find("\"new\"").unwrap() < rendered.find("\"old\"").unwrap());
    let parsed = statement(&rendered, dialect);
    assert_eq!(parsed.with_clause().unwrap().len(), 2);
    assert_eq!(rendered, parsed.deparse_sql(dialect).unwrap());
}

#[test]
fn reports_dialect_mismatch_without_modifying_statement() {
    let value = statement("select 1", Dialect::postgres());
    let original = value.deparse_sql(Dialect::postgres()).unwrap();
    let error = value.deparse_sql(Dialect::sqlite()).unwrap_err();
    assert!(error.is_dialect_mismatch());
    assert_eq!(error.dialect(), Dialect::sqlite());
    assert_eq!(original, value.deparse_sql(Dialect::postgres()).unwrap());
}

