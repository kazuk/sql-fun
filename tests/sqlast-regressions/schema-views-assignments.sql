CREATE TABLE public.items (id int GENERATED ALWAYS AS IDENTITY, calc int GENERATED ALWAYS AS (42) STORED, other int GENERATED BY DEFAULT AS IDENTITY);
CREATE VIEW public.v AS SELECT id AS key, calc, other FROM public.items;
CREATE TABLE public.cast_items (id int, value varchar);
CREATE VIEW public.cast_same AS SELECT id::int AS key FROM public.cast_items;
CREATE VIEW public.cast_different AS SELECT id::bigint AS key FROM public.cast_items;
CREATE VIEW public.cast_star AS SELECT *, id::int AS key FROM public.cast_items;
CREATE VIEW public.cast_typmod AS SELECT value::varchar(5) AS key FROM public.cast_items;
CREATE TABLE public.duplicate_items (a int, b int[]);
CREATE VIEW public.duplicate_view AS SELECT a AS x, a AS y, b AS p, b AS q FROM public.duplicate_items;
CREATE TABLE public.effective_items (id integer GENERATED ALWAYS AS IDENTITY, value integer DEFAULT 7, calc integer GENERATED ALWAYS AS (42) STORED);
CREATE VIEW public.effective_view AS SELECT id AS key, value, calc, value + 1 AS computed FROM public.effective_items;
